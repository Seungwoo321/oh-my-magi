import fs from 'node:fs';
import path from 'node:path';
import { createPublicKey } from 'node:crypto';
import { loadSigningEnvironment } from './load-signing-env.mjs';
import { storageCompatibility, validateBuildReceipt, signReleaseDocument } from './release-contract.mjs';

const [artifact, url, minimumMacos, output] = process.argv.slice(2);
if (!artifact || !url || !minimumMacos || !output) throw new Error('Usage: node scripts/create-release-manifest.mjs ARTIFACT HTTPS_URL MINIMUM_MACOS OUTPUT');
const { privateKey, publicKey } = loadSigningEnvironment();
const trust = JSON.parse(fs.readFileSync('src-tauri/release-trust.json', 'utf8'));
if (!createPublicKey(trust.manifestPublicKeyPem).export({ type: 'spki', format: 'der' }).equals(publicKey.export({ type: 'spki', format: 'der' }))) throw new Error('Manifest key differs from the embedded release trust.');
const endpoint = new URL(url);
if (endpoint.protocol !== 'https:' || endpoint.username || endpoint.password || endpoint.hash || !trust.allowedDownloadHosts.includes(endpoint.hostname)) throw new Error('Artifact URL must match a configured trusted HTTPS release host.');
if (endpoint.hostname !== 'github.com' || endpoint.search || !/^\/Seungwoo321\/oh-my-magi\/releases\/download\/[^/]+\/[^/]+$/.test(endpoint.pathname) || /%2f|%5c/i.test(endpoint.pathname)) throw new Error('Artifact URL must be a versioned release asset in the approved GitHub repository.');
const config = JSON.parse(fs.readFileSync('src-tauri/tauri.conf.json', 'utf8'));
const version = config.version;
if (minimumMacos !== config.bundle?.macOS?.minimumSystemVersion) throw new Error('Manifest minimum macOS must match the application build contract.');
const receipt = JSON.parse(fs.readFileSync('.local/release/build-verification.json', 'utf8'));
if (!receipt.codeSignatureValid || !receipt.gatekeeperAccepted || !receipt.notarizationStapleValid || receipt.localSigned) throw new Error('A fully verified notarized build is required.');
const compatibility = storageCompatibility(process.cwd());
const identity = validateBuildReceipt(receipt, { artifact, version, compatibility });
const target = receipt.target;
if (!['darwin-aarch64', 'darwin-x86_64'].includes(target) || path.resolve(artifact) !== path.resolve(receipt.archive)) throw new Error('Artifact differs from the verified release build.');
const updaterSignature = fs.readFileSync(`${artifact}.sig`, 'utf8').trim();
const manifest = { version, target, minimum_macos: minimumMacos, schema_min: compatibility.schemaMin, schema_max: compatibility.schemaMax, payload: { url, sha256: identity.sha256, size: identity.size, signature: updaterSignature }, notes: '' };
const document = signReleaseDocument(manifest, privateKey, publicKey);
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(output, JSON.stringify(document, null, 2) + '\n', { flag: 'wx', mode: 0o644 });
console.log('Signed release manifest created and its independent Ed25519 signature verified.');
